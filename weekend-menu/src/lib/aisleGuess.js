// Best-effort first guess of an aisle for a new product (F8). The user can change it once; it is remembered.
const RULES = [
  ['Бакалея', /(перец молот|черный перец|паприк|специ|лавров|^соль|масло раст|подсолн|оливков)/],
  ['Мясо и птица', /(груд|кур|кури|филе|фарш|говя|свин|баран|стейк|мяс|колбас|копч|сосис|ветчин|бекон|индей|печен)/],
  ['Молочное', /(молок|сметан|сыр|творог|кефир|йогурт|сливк|масло слив|сливочн|ряженк|яйц|яйко)/],
  ['Овощи и фрукты', /(лук|морков|картоф|капуст|свекл|помидор|томат|огур|перец|перчик|чеснок|зелен|укроп|петруш|кинз|салат|лимон|яблок|банан|гранат|апельсин|баклаж|кабач|гриб|авокадо|редис|сельдер|шпинат|ягод|фрукт|овощ)/],
  ['Консервы и соусы', /(маслин|олив|консерв|горош|кукуруз|фасол|соус|майонез|кетчуп|горчиц|паст|томатн|огурц мар|каперс|тушен)/],
  ['Хлеб', /(хлеб|батон|лаваш|булк|багет|лепеш)/],
  ['Заморозка', /(заморож|пельмен|мороженое|вареник)/],
  ['Бакалея', /(рис|греч|макарон|мук|сахар|соль|перец молот|специ|лавров|масло раст|подсолн|оливков|круп|овсян|чай|кофе|уксус|спагет|лапш|булгур|кускус|дрожж|сода|приправ)/],
];

export function guessAisle(name) {
  const n = name.toLowerCase().replace(/ё/g, 'е');
  for (const [aisle, re] of RULES) if (re.test(n)) return aisle;
  return 'Другое';
}
